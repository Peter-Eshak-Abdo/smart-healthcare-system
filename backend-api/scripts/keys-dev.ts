import { generateKeyPairSync, randomBytes } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '../..');

function genEd25519OneLinePem(): string {
  const { privateKey } = generateKeyPairSync('ed25519');
  const pem = privateKey.export({ format: 'pem', type: 'pkcs8' }) as string;
  return pem.trim().replace(/\r?\n/g, '\\n');
}

function parseEnvFile(filePath: string): Map<string, string> {
  const map = new Map<string, string>();
  if (!fs.existsSync(filePath)) return map;
  const raw = fs.readFileSync(filePath, 'utf8');
  for (const line of raw.split(/\r?\n/)) {
    const t = line.trim();
    if (!t || t.startsWith('#')) continue;
    const eq = t.indexOf('=');
    if (eq <= 0) continue;
    const key = t.slice(0, eq).trim();
    let val = t.slice(eq + 1).trim();
    if (
      (val.startsWith('"') && val.endsWith('"')) ||
      (val.startsWith("'") && val.endsWith("'"))
    ) {
      val = val.slice(1, -1);
    }
    map.set(key, val);
  }
  return map;
}

function formatEnvValue(key: string, val: string): string {
  const needsQuotes =
    val.includes('\\n') ||
    val.includes('\n') ||
    val.includes(' ') ||
    key.includes('PRIVATE_KEY') ||
    key.includes('PUBLIC_KEY');
  return needsQuotes ? `"${val.replace(/\r?\n/g, '\\n')}"` : val;
}

function writeMergedEnv(filePath: string, additions: Record<string, string | undefined>, overwriteExisting = false): void {
  const map = parseEnvFile(filePath);
  for (const [k, raw] of Object.entries(additions)) {
    if (!raw) continue;
    if (!overwriteExisting && map.has(k)) continue;
    map.set(k, raw);
  }
  const lines = [
    '# Auto-generated by `npm run keys:dev` (git-ignored, never commit)',
    ...Array.from(map.entries()).map(([k, v]) => `${k}=${formatEnvValue(k, v)}`),
  ];
  fs.writeFileSync(filePath, `${lines.join('\n')}\n`, 'utf8');
  process.stdout.write(`Configured ${path.relative(rootDir, filePath)} (${map.size} keys)\n`);
}

function main() {
  const backendEnvPath = path.resolve(rootDir, 'backend-api/.env');
  const webEnvPath = path.resolve(rootDir, 'web-admin/.env.local');
  const rootEnvLocalPath = path.resolve(rootDir, '.env.local');

  const rootKv = parseEnvFile(rootEnvLocalPath);

  const projectId =
    rootKv.get('FIREBASE_PROJECT_ID') ??
    rootKv.get('project_id') ??
    rootKv.get('NEXT_PUBLIC_FIREBASE_Project_ID') ??
    rootKv.get('NEXT_PUBLIC_FIREBASE_PROJECT_ID');
  const clientEmail = rootKv.get('FIREBASE_CLIENT_EMAIL') ?? rootKv.get('client_email');
  const privateKey = rootKv.get('FIREBASE_PRIVATE_KEY') ?? rootKv.get('private_key');
  const vercelOrigin = rootKv.get('VERCEL_URL_ADMIN_WEB');

  writeMergedEnv(
    backendEnvPath,
    {
      APP_ENV: 'local',
      PORT: '4000',
      APP_VERSION: '1.0.0',
      GIT_COMMIT: 'dev',
      WEB_ORIGIN: vercelOrigin ?? 'http://localhost:3000',
      FIREBASE_PROJECT_ID: projectId,
      FIREBASE_CLIENT_EMAIL: clientEmail,
      FIREBASE_PRIVATE_KEY: privateKey,
      UPSTASH_REDIS_REST_URL: rootKv.get('UPSTASH_REDIS_REST_URL'),
      UPSTASH_REDIS_REST_TOKEN: rootKv.get('UPSTASH_REDIS_REST_TOKEN'),
      KEK_CURRENT_ID: 'k1',
      KEK_K1: randomBytes(32).toString('base64'),
      BLIND_INDEX_KEY: randomBytes(32).toString('base64'),
      RX_SIGNING_KEY_ID: 'rx-2026-11',
      RX_SIGNING_PRIVATE_KEY: genEd25519OneLinePem(),
      EMERGENCY_CARD_SIGNING_KEY_ID: 'ec-2026-11',
      EMERGENCY_CARD_SIGNING_PRIVATE_KEY: genEd25519OneLinePem(),
      BIOMETRIC_TRANSFORM_SECRET: randomBytes(32).toString('base64'),
      BIOMETRIC_TRANSFORM_KEY_VERSION: '1',
    },
    false,
  );

  writeMergedEnv(
    webEnvPath,
    {
      NEXT_PUBLIC_API_BASE_URL: 'http://localhost:4000',
      NEXT_PUBLIC_APP_VERSION: '1.0.0',
      NEXT_PUBLIC_FIREBASE_API_KEY:
        rootKv.get('NEXT_PUBLIC_FIREBASE_API_KEY') ?? rootKv.get('NEXT_PUBLIC_FIREBASE_API_Key'),
      NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN:
        rootKv.get('NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN') ??
        rootKv.get('NEXT_PUBLIC_FIREBASE_Auth_Domain'),
      NEXT_PUBLIC_FIREBASE_PROJECT_ID: projectId,
      NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET:
        rootKv.get('NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET') ??
        rootKv.get('NEXT_PUBLIC_FIREBASE_storage_Bucket'),
      NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID:
        rootKv.get('NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID') ??
        rootKv.get('NEXT_PUBLIC_FIREBASE_Messaging_Sender_ID'),
      NEXT_PUBLIC_FIREBASE_APP_ID:
        rootKv.get('NEXT_PUBLIC_FIREBASE_APP_ID') ?? rootKv.get('NEXT_PUBLIC_FIREBASE_App_ID'),
      FIREBASE_PROJECT_ID: projectId,
      FIREBASE_CLIENT_EMAIL: clientEmail,
      FIREBASE_PRIVATE_KEY: privateKey,
    },
    false,
  );
}

main();
